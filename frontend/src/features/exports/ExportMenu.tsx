import { t } from '~/utils/i18n'
import { DropdownMenu } from '@kobalte/core/dropdown-menu'
import { createSignal, For } from 'solid-js'
import { toast } from '~/components/feedback/toast'
import { Icon } from '~/components/ui/Icon'
import { Spinner } from '~/components/ui/Primitives'
import { getErrorMessage } from '~/services/api'
import { examsApi, type ExportKind } from '~/services/exams.api'
import { saveBlob } from '~/utils/download'

const items: { kind: ExportKind; label: string; hint: string }[] = [
  { kind: 'export/pdf', get label() { return t('Exam paper (PDF)') }, get hint() { return t('Print-ready, no answers') } },
  { kind: 'export/word', get label() { return t('Exam paper (Word)') }, get hint() { return t('Editable .docx') } },
  { kind: 'answer-key/pdf', get label() { return t('Answer key (PDF)') }, get hint() { return t('Confidential') } },
  { kind: 'answer-key/word', get label() { return t('Answer key (Word)') }, get hint() { return t('Confidential') } },
]

/** Downloads exam/answer-key documents generated by the API (PDF via QuestPDF, Word via OpenXML). */
export function ExportMenu(props: { examId: string; disabled?: boolean }) {
  const [busy, setBusy] = createSignal(false)

  const download = async (kind: ExportKind) => {
    setBusy(true)
    try {
      const { blob, fileName } = await examsApi.download(props.examId, kind)
      saveBlob(blob, fileName)
    } catch (err) {
      toast.error(t('Export failed'), getErrorMessage(err))
    } finally {
      setBusy(false)
    }
  }

  return (
    <DropdownMenu>
      <DropdownMenu.Trigger
        disabled={props.disabled || busy()}
        class="action-button inline-flex h-10 items-center gap-2 bg-white px-4 text-sm text-ink enabled:hover:bg-brand-50"
      >
        {busy() ? <Spinner class="size-4" /> : <Icon name="download" />}
        {t('Export')}
        <DropdownMenu.Icon><Icon name="down" class="size-3.5" /></DropdownMenu.Icon>
      </DropdownMenu.Trigger>
      <DropdownMenu.Portal>
        <DropdownMenu.Content class="panel z-50 min-w-[14rem] p-1 outline-none">
          <For each={items}>
            {(item) => (
              <DropdownMenu.Item
                class="flex cursor-pointer flex-col rounded-md px-3 py-2 text-sm outline-none data-[highlighted]:bg-slate-100"
                onSelect={() => download(item.kind)}
              >
                <span class="font-medium text-slate-900">{item.label}</span>
                <span class="text-xs text-slate-500">{item.hint}</span>
              </DropdownMenu.Item>
            )}
          </For>
        </DropdownMenu.Content>
      </DropdownMenu.Portal>
    </DropdownMenu>
  )
}
